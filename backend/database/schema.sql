CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(100) NOT NULL,
  email VARCHAR(100) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  phone_number VARCHAR(20),
  role VARCHAR(20) NOT NULL DEFAULT 'PASSENGER'
    CHECK (role IN ('PASSENGER', 'ADMIN')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.routes_schedules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  origin_city VARCHAR(100) NOT NULL,
  destination_city VARCHAR(100) NOT NULL,
  departure_date DATE NOT NULL,
  departure_time TIME NOT NULL,
  arrival_time TIME NOT NULL,
  base_price NUMERIC(10,2) NOT NULL CHECK (base_price >= 0),
  map_coord_x INTEGER,
  map_coord_y INTEGER,
  image_url VARCHAR(255),
  UNIQUE (origin_city, destination_city, departure_date, departure_time)
);

CREATE TABLE IF NOT EXISTS public.vehicles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehicle_name VARCHAR(100) NOT NULL UNIQUE,
  vehicle_type VARCHAR(50) NOT NULL,
  total_seats INTEGER NOT NULL CHECK (total_seats > 0),
  amenities JSONB NOT NULL DEFAULT '[]'::JSONB,
  image_url VARCHAR(255),
  price_modifier NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (price_modifier >= 0)
);

CREATE TABLE IF NOT EXISTS public.drivers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  driver_name VARCHAR(100) NOT NULL UNIQUE,
  photo_url VARCHAR(255),
  rating NUMERIC(2,1) CHECK (rating >= 0 AND rating <= 5),
  total_trip_quota INTEGER NOT NULL CHECK (total_trip_quota >= 0),
  remaining_trip_quota INTEGER NOT NULL CHECK (
    remaining_trip_quota >= 0 AND remaining_trip_quota <= total_trip_quota
  )
);

CREATE TABLE IF NOT EXISTS public.bookings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_code VARCHAR(20) NOT NULL UNIQUE,
  user_id BIGINT NOT NULL REFERENCES public.users(id),
  schedule_id BIGINT NOT NULL REFERENCES public.routes_schedules(id),
  vehicle_id BIGINT NOT NULL REFERENCES public.vehicles(id),
  driver_id BIGINT NOT NULL REFERENCES public.drivers(id),
  passenger_name VARCHAR(100) NOT NULL,
  passenger_identity_number VARCHAR(50) NOT NULL,
  passenger_phone VARCHAR(20) NOT NULL,
  seat_number VARCHAR(10) NOT NULL,
  total_amount NUMERIC(10,2) NOT NULL CHECK (total_amount >= 0),
  booking_status VARCHAR(30) NOT NULL DEFAULT 'PENDING_PAYMENT'
    CHECK (booking_status IN ('PENDING_PAYMENT','WAITING_VALIDATION','PAYMENT_FAILED','CONFIRMED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS bookings_active_seat_unique
  ON public.bookings(schedule_id, vehicle_id, seat_number)
  WHERE booking_status IN ('PENDING_PAYMENT','WAITING_VALIDATION','CONFIRMED');
CREATE INDEX IF NOT EXISTS bookings_user_created_idx
  ON public.bookings(user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id BIGINT NOT NULL REFERENCES public.bookings(id),
  payment_method VARCHAR(50) NOT NULL,
  proof_image_url VARCHAR(255) NOT NULL,
  payment_status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
    CHECK (payment_status IN ('PENDING','SUCCESS','REJECTED')),
  admin_notes TEXT,
  validated_by BIGINT REFERENCES public.users(id),
  validated_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS payments_status_created_idx
  ON public.payments(payment_status, created_at DESC);

CREATE TABLE IF NOT EXISTS public.e_tickets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id BIGINT NOT NULL UNIQUE REFERENCES public.bookings(id),
  ticket_number VARCHAR(30) NOT NULL UNIQUE,
  qr_code_data TEXT NOT NULL,
  issued_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

