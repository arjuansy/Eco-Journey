CREATE OR REPLACE FUNCTION public.validate_payment(
  p_payment_id BIGINT,
  p_is_success BOOLEAN,
  p_notes TEXT,
  p_admin_id BIGINT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_payment public.payments%ROWTYPE;
  v_booking public.bookings%ROWTYPE;
BEGIN
  SELECT * INTO v_payment
  FROM public.payments
  WHERE id = p_payment_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Payment not found';
  END IF;
  IF v_payment.payment_status <> 'PENDING' THEN
    RAISE EXCEPTION 'Payment has already been processed';
  END IF;

  SELECT * INTO v_booking
  FROM public.bookings
  WHERE id = v_payment.booking_id
  FOR UPDATE;

  IF p_is_success THEN
    UPDATE public.drivers
    SET remaining_trip_quota = remaining_trip_quota - 1
    WHERE id = v_booking.driver_id AND remaining_trip_quota > 0;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Driver trip quota is exhausted';
    END IF;

    UPDATE public.payments
    SET payment_status = 'SUCCESS',
        admin_notes = p_notes,
        validated_by = p_admin_id,
        validated_at = NOW()
    WHERE id = v_payment.id;

    UPDATE public.bookings
    SET booking_status = 'CONFIRMED'
    WHERE id = v_booking.id;

    INSERT INTO public.e_tickets(booking_id, ticket_number, qr_code_data)
    VALUES (v_booking.id, 'TKT-' || v_booking.booking_code, v_booking.booking_code)
    ON CONFLICT (booking_id) DO NOTHING;
  ELSE
    UPDATE public.payments
    SET payment_status = 'REJECTED',
        admin_notes = p_notes,
        validated_by = p_admin_id,
        validated_at = NOW()
    WHERE id = v_payment.id;

    UPDATE public.bookings
    SET booking_status = 'PAYMENT_FAILED'
    WHERE id = v_booking.id;
  END IF;

  SELECT * INTO v_payment FROM public.payments WHERE id = v_payment.id;
  SELECT * INTO v_booking FROM public.bookings WHERE id = v_booking.id;
  RETURN jsonb_build_object('payment', to_jsonb(v_payment), 'booking', to_jsonb(v_booking));
END;
$$;

REVOKE EXECUTE ON FUNCTION public.validate_payment(BIGINT, BOOLEAN, TEXT, BIGINT)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.validate_payment(BIGINT, BOOLEAN, TEXT, BIGINT)
  TO service_role;
